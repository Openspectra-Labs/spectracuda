"""Emit the thresh_wq soft-demapper table for fpga/rtl/rx/demapper_soft.v
from spectracuda's own Modem.soft_table() (the committed reference).

    rtl/generated/soft_table.mem   2048 x 36-bit hex, address {mod[1:0], idx[8:0]}
                                   mod: 0 QPSK, 1 16QAM, 2 64QAM, 3 unused (0)
                                   data: {3'b0, T2[10:0], T1[10:0], T0[10:0]},
                                   Tj = round(16 t) for axis bit j (0 = MSB)
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))          # fpga/gen
sys.path.insert(0, os.path.join(HERE, "..", ".."))
from spectracuda.modem import Modem

def main():
    out = os.path.join(HERE, "..", "rtl", "generated", "soft_table.mem")
    rows = []
    for mod in ("qpsk", "qam16", "qam64", None):
        if mod is None:
            rows += [0] * 512
            continue
        tab = Modem(mod).soft_table()
        for r in tab:
            w = 0
            for j in range(3):
                w |= (int(r[j]) & 0x7FF) << (11 * j)
            rows.append(w)
    with open(out, "w") as f:
        f.write("".join(f"{w:09x}\n" for w in rows))
    vh = os.path.join(os.path.dirname(out), "soft_table.vh")
    with open(vh, "w") as f:
        f.write("// GENERATED by fpga/gen/emit_soft_table.py from Modem.soft_table() -- do not edit\n")
        f.write("`ifndef SOFT_TABLE_VH\n`define SOFT_TABLE_VH\n")
        f.write(f'`define SOFT_TABLE_MEM "{os.path.abspath(out)}"\n')
        for m, sh in Modem.SOFT_TABLE_SHIFT.items():
            f.write(f"`define SOFT_TABLE_SHIFT_{m.upper()} {sh}\n")
        f.write("`endif\n")
    print(f"wrote {os.path.relpath(out)}: {len(rows)} entries, and {os.path.relpath(vh)}")

if __name__ == "__main__":
    main()

"""Emit Verilog headers (.vh) from a constructed `Ofdm` object.

The Verilog counterpart of `emit.py`. Same architecture, different
formatter: Python generates constants, tables and ROM contents; the
hand-written blocks in `hls/rtl/src/` `\\`include` them and never change
per configuration.

This is not a novel arrangement -- `reference/openofdm` already does it
(`scripts/gen_deinter_lut.py` -> `verilog/deinter_lut.coe`), which is
part of why the language change cost the generator architecture nothing.

## Angle representation

Phase is a signed fraction of a FULL TURN, not radians, held in
`ANGLE_W` bits with two's-complement wraparound. That is the natural
form for a phase accumulator (rollover IS modulo-2*pi, free), and it
makes the CFO increment a shift instead of a multiply:

    cfo        = angle(P) / pi                     (spectracuda's definition)
    d_phase    = -2*pi*cfo / fft_size              (radians per sample)
    d_phase/2pi = -(angle(P)/2pi) / (fft_size/2)
                = -angle_turns >> log2(L)

So with L a power of two, the whole increment computation is a negate
and a right shift. See `hls/rtl/src/cfo_correct.v`.
"""
from __future__ import annotations

import os
from typing import List

import numpy as np

# The pinned golden model, NOT the working-tree spectracuda -- see hls/rtl/golden_ref.py.
from hls.rtl import golden_ref  # noqa: E402
golden_ref.use()
from spectracuda.pipeline import Ofdm

from .emit import validate

ANGLE_W = 16      # phase word: 2**ANGLE_W == one full turn
CORDIC_STAGES = 16
SAMPLE_W = 16


def _banner(title: str, ofdm: Ofdm) -> str:
    return (
        "// ============================================================\n"
        f"// {title}\n"
        "//\n"
        "// GENERATED by hls/gen/emit_rtl.py from a spectracuda Ofdm object.\n"
        "// Do not edit -- regenerate with `make headers` in hls/rtl/.\n"
        "//\n"
        f"//   fft_size={ofdm.fft_size} cp_len={ofdm.cp_len} "
        f"n_data={ofdm.grid.n_data} n_pilot={ofdm.grid.n_pilot}\n"
        f"//   n_training_symbols={ofdm.n_training_symbols}\n"
        "// ============================================================\n"
    )


def emit_rtl(ofdm: Ofdm, out_dir: str, partial: bool = False) -> List[str]:
    validate(ofdm, partial=partial)
    os.makedirs(out_dir, exist_ok=True)
    written: List[str] = []

    def write(name: str, text: str) -> None:
        path = os.path.join(out_dir, name)
        with open(path, "w") as f:
            f.write(text)
        written.append(path)

    L = ofdm.fft_size // 2
    if L & (L - 1):
        raise ValueError(
            f"fft_size/2 = {L} is not a power of two; the CFO phase "
            f"increment relies on a shift. Widen emit_rtl to emit a "
            f"reciprocal constant before allowing this."
        )
    log2_l = int(np.log2(L))

    # ---- ofdm_params.vh ----
    p = _banner("ofdm_params.vh -- geometry", ofdm)
    p += "`ifndef OFDM_PARAMS_VH\n`define OFDM_PARAMS_VH\n\n"
    for k, v in [
        ("FFT_SIZE", ofdm.fft_size),
        ("CP_LEN", ofdm.cp_len),
        ("SLOT_LEN", ofdm.slot_len),
        ("N_DATA", ofdm.grid.n_data),
        ("N_PILOT", ofdm.grid.n_pilot),
        ("N_NULL", int(ofdm.grid.null_indices.size)),
        ("N_TRAINING", ofdm.n_training_symbols),
        ("SC_LAG", L),
        ("SC_LOG2_LAG", log2_l),
        ("SAMPLE_W", SAMPLE_W),
        ("ANGLE_W", ANGLE_W),
        ("CORDIC_STAGES", CORDIC_STAGES),
    ]:
        p += f"`define {k} {int(v)}\n"
    p += "\n`endif\n"
    write("ofdm_params.vh", p)

    # ---- cordic_table.vh ----
    # atan(2^-i), expressed in the same turn-fraction units as the phase
    # accumulator. Generated rather than typed: sixteen hand-transcribed
    # constants is sixteen chances to put a radian where a turn belongs,
    # and the failure would look like a small CFO bias rather than an
    # obvious break.
    scale = float(1 << ANGLE_W)
    atan_turns = [np.arctan(2.0 ** -i) / (2 * np.pi) for i in range(CORDIC_STAGES)]
    atan_codes = [int(np.floor(a * scale + 0.5)) for a in atan_turns]

    # CORDIC processing gain: prod sqrt(1 + 2^-2i). Rotation mode must
    # pre-scale by 1/K or the output magnitude comes out 1.647x large.
    # Vectoring mode does not care -- only the angle is used there.
    k_gain = float(np.prod([np.sqrt(1 + 2.0 ** (-2 * i)) for i in range(CORDIC_STAGES)]))
    inv_k = 1.0 / k_gain
    inv_k_q15 = int(np.floor(inv_k * (1 << 15) + 0.5))

    c = _banner("cordic_table.vh -- arctan LUT + gain constant", ofdm)
    c += "`ifndef CORDIC_TABLE_VH\n`define CORDIC_TABLE_VH\n\n"
    c += (
        f"// atan(2^-i) as a fraction of a full turn, scaled by 2^{ANGLE_W}.\n"
        f"// One full turn == {1 << ANGLE_W}; a half turn (pi) == "
        f"{1 << (ANGLE_W - 1)}.\n"
    )
    c += f"`define CORDIC_ATAN_INIT \\\n"
    for i, code in enumerate(atan_codes):
        sep = " \\\n" if i < len(atan_codes) - 1 else "\n"
        c += f"    atan_lut[{i}] = {ANGLE_W}'sd{code};{sep}"
    c += (
        f"\n// CORDIC gain K = prod sqrt(1+2^-2i) = {k_gain:.9f} over "
        f"{CORDIC_STAGES} stages.\n"
        f"// Rotation mode pre-scales by 1/K = {inv_k:.9f} (Q15).\n"
        f"`define CORDIC_INV_K 16'sd{inv_k_q15}\n"
    )
    c += "\n`endif\n"
    write("cordic_table.vh", c)
    return written


def main() -> None:
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.normpath(os.path.join(here, "..", "rtl", "src", "generated"))
    from .golden import CFG
    ofdm = Ofdm(**CFG)
    # partial=True while the FEC blocks are still being written.
    for path in emit_rtl(ofdm, out, partial=True) + emit_chanest(ofdm, out) + emit_eq(ofdm, out) + emit_demap(ofdm, out) + emit_crc(ofdm, out) + emit_grid(ofdm, out) + emit_header(ofdm, out):
        print(f"  wrote {os.path.relpath(path, os.path.join(here, '..'))}")


def emit_grid(ofdm: Ofdm, out_dir: str) -> list:
    """Subcarrier type map for grid_extract.v.

    cp_fft streams all N bins out in natural order; splitting them into
    data / pilot / null is pure index selection in Python
    (`ResourceGrid.extract_data` is `grid[:, data_indices]`), so in fabric
    it is a per-bin classification against a ROM. The ROM is DERIVED from
    the live ResourceGrid rather than transcribed: the pilot pattern is
    not a regular stride (indices 1,33,65,97,159,191,223,255 for fft=256
    -- note the gap where DC and the guard band sit), and hand-writing it
    is exactly the kind of thing that silently decodes garbage.

    Also emits whether every pilot is the same constant. It is (+1 for
    this configuration), which lets pilot_cpe.v skip the divide by the
    known pilot value entirely -- the ratio IS the equalized pilot.
    """
    import numpy as _np
    os.makedirs(out_dir, exist_ok=True)

    n_fft = int(ofdm.fft_size)
    pilots = _np.asarray(ofdm.grid.pilot_indices).astype(int)
    datas = _np.asarray(ofdm.grid.data_indices).astype(int)

    NULL, DATA, PILOT = 0, 1, 2
    sctype = _np.full(n_fft, NULL, dtype=int)
    sctype[datas] = DATA
    sctype[pilots] = PILOT
    if int((sctype == DATA).sum()) != len(datas) or \
       int((sctype == PILOT).sum()) != len(pilots):
        raise ValueError("data and pilot index sets overlap")

    mem = os.path.join(out_dir, "grid_type.mem")
    with open(mem, "w") as f:
        for t in sctype:
            f.write(f"{t:01x}\n")

    pv = _np.asarray(ofdm.pilot_values).ravel()
    uniform = bool(_np.all(pv == pv[0]))
    if not uniform:
        raise ValueError(
            "pilot_values are not a single constant; pilot_cpe.v assumes "
            "they are and skips the divide -- emit a pilot ROM first")
    pv0 = complex(pv[0])
    if abs(pv0 - 1.0) > 1e-12:
        raise ValueError(f"pilot value {pv0} is not +1; pilot_cpe.v assumes +1")

    hdr = os.path.join(out_dir, "grid_params.vh")
    with open(hdr, "w") as f:
        f.write("// ============================================================\n")
        f.write("// grid_params.vh -- subcarrier type map\n")
        f.write("//\n")
        f.write("// GENERATED by hls/gen/emit_rtl.py from a spectracuda Ofdm\n")
        f.write("// object. Do not edit -- regenerate with `make headers`.\n")
        f.write(f"//   fft_size={n_fft} n_data={len(datas)} n_pilot={len(pilots)}\n")
        f.write(f"//   pilot bins: {[int(x) for x in pilots]}\n")
        f.write("// ============================================================\n")
        f.write("`ifndef GRID_PARAMS_VH\n`define GRID_PARAMS_VH\n\n")
        f.write(f"`define GRID_N_FFT {n_fft}\n")
        f.write(f"`define GRID_N_DATA {len(datas)}\n")
        f.write(f"`define GRID_N_PILOT {len(pilots)}\n")
        f.write("`define GRID_TYPE_NULL 0\n")
        f.write("`define GRID_TYPE_DATA 1\n")
        f.write("`define GRID_TYPE_PILOT 2\n")
        f.write("// Every pilot is +1, so the CPE ratio is the equalized\n")
        f.write("// pilot itself and no division is needed.\n")
        f.write("`define GRID_PILOT_IS_ONE 1\n")
        # pilot_cpe.v never forms the mean. angle(sum/N) == angle(sum) for
        # real N>0, so the sum goes straight into the CORDIC; and the
        # reliability gate |mean| > T becomes |sum|^2 > (T*N)^2, which is
        # integer-only. Emitted at Q(2*frac) to match a Q(frac) input.
        frac = 12
        thresh = 0.05          # ofdm.py:_decode_payload_from_header
        tsq = int(round((thresh * len(pilots)) ** 2 * (1 << (2 * frac))))
        f.write(f"`define GRID_CPE_Q {frac}\n")
        f.write(f"// |sum|^2 gate: (|mean| > {thresh}) with n_pilot={len(pilots)}\n")
        f.write(f"`define GRID_CPE_THRESH_SQ {tsq}\n")
        # Magnitude form of the same gate. pilot_cpe.v compares the
        # CORDIC's |sum| against this instead of squaring: squaring cost
        # two 22x22 multiplies and an 11.3 ns path for what is only an
        # ordering test. The CORDIC is already running on this exact
        # vector for the angle, so the magnitude is free.
        #
        # K is the vectoring-CORDIC gain, prod sqrt(1+2^-2i), which
        # scales the magnitude it returns.
        stages = 16
        K = 1.0
        for i in range(stages):
            K *= (1.0 + 4.0 ** (-i)) ** 0.5
        tmag = int(round(K * thresh * len(pilots) * (1 << frac)))
        f.write(f"// |sum| gate, same decision, K={K:.6f} folded in\n")
        f.write(f"`define GRID_CPE_THRESH_MAG {tmag}\n")
        f.write(f'`define GRID_TYPE_MEM "{mem}"\n\n')
        f.write("`endif\n")
    return [hdr, mem]


def emit_header(ofdm: Ofdm, out_dir: str) -> list:
    """Scramble mask + field code tables for header_decode.v.

    THE MASK MUST BE GENERATED, NOT REIMPLEMENTED. It is
    `np.random.default_rng(42).integers(0, 2, 112)` -- numpy's PCG64
    stream. There is no sane way to reproduce that in Verilog, and an
    LFSR that merely looks random would decode every header to garbage.
    So the live HeaderCodec's own mask is dumped here.

    Also emitted: which mod_scheme / crc / fec codes are legal, and the
    bits-per-symbol for each modulation, so header_decode.v can reject a
    corrupt header the same way HeaderCodec.decode_bits raises on an
    unknown code, and so the payload demapper can be told its width.
    """
    import numpy as _np
    from spectracuda.framing.header import (
        HeaderCodec, MOD_SCHEME_CODES, CRC_SCHEME_CODES, FEC_SCHEME_CODES)
    os.makedirs(out_dir, exist_ok=True)

    codec = HeaderCodec()
    mask = _np.asarray(codec._scramble_mask).astype(int).ravel()
    n = int(codec.HEADER_LEN_BITS)
    if len(mask) != n:
        raise ValueError(f"scramble mask is {len(mask)} bits, expected {n}")

    mem = os.path.join(out_dir, "header_mask.mem")
    with open(mem, "w") as f:
        for b in mask:
            f.write(f"{int(b):01x}\n")

    bps = {"bpsk": 1, "qpsk": 2, "qam16": 4, "qam64": 6, "qam256": 8}
    max_mod = max(MOD_SCHEME_CODES.values())
    bps_mem = os.path.join(out_dir, "header_bps.mem")
    with open(bps_mem, "w") as f:
        for code in range(max_mod + 1):
            name = {v: k for k, v in MOD_SCHEME_CODES.items()}.get(code)
            f.write(f"{bps.get(name, 0):02x}\n")

    def _bitset(codes, width):
        v = 0
        for c in codes:
            if c < width:
                v |= 1 << int(c)
        return v

    # Header content bits are SPREAD across the header symbol's data
    # slots (np.linspace + unique, ofdm.py:443), not packed into the
    # first 112 -- deliberate frequency diversity, and part of the same
    # PAPR fix as the scrambling. So the block needs a per-slot select
    # map, not a bit count.
    pos = _np.asarray(ofdm._header_positions_flat).astype(int).ravel()
    total_slots = int(ofdm.grid.n_data) * int(ofdm.num_symbols_header)
    sel = _np.zeros(total_slots, dtype=int)
    sel[pos] = 1
    if int(sel.sum()) != n:
        raise ValueError(f"header select map has {int(sel.sum())} slots, expected {n}")
    sel_mem = os.path.join(out_dir, "header_sel.mem")
    with open(sel_mem, "w") as f:
        for b in sel:
            f.write(f"{int(b):01x}\n")

    hdr = os.path.join(out_dir, "header_params.vh")
    with open(hdr, "w") as f:
        f.write("// ============================================================\n")
        f.write("// header_params.vh -- 112-bit header codec constants\n")
        f.write("//\n")
        f.write("// GENERATED by hls/gen/emit_rtl.py from the live HeaderCodec.\n")
        f.write("// Do not edit -- regenerate with `make headers`.\n")
        f.write("//   byte 0     protocol/version\n")
        f.write("//   bytes 1-2  payload length in BITS\n")
        f.write("//   byte 3     mod_scheme\n")
        f.write("//   byte 4     crc(3b) | fec0(5b)\n")
        f.write("//   byte 5     fec1\n")
        f.write("//   bytes 6-13 user data\n")
        f.write("// ============================================================\n")
        f.write("`ifndef HEADER_PARAMS_VH\n`define HEADER_PARAMS_VH\n\n")
        f.write(f"`define HDR_LEN_BITS {n}\n")
        f.write(f"`define HDR_LEN_BYTES {n // 8}\n")
        f.write(f"`define HDR_PROTOCOL_VERSION {int(codec.PROTOCOL_VERSION)}\n")
        f.write(f'`define HDR_MASK_MEM "{mem}"\n')
        f.write(f'`define HDR_BPS_MEM "{bps_mem}"\n')
        f.write(f"`define HDR_MOD_CODE_MAX {max_mod}\n")
        f.write(f"`define HDR_TOTAL_SLOTS {total_slots}\n")
        f.write(f'`define HDR_SEL_MEM "{sel_mem}"\n')
        f.write("// One bit per code: set = that code is a known scheme.\n")
        f.write(f"`define HDR_MOD_VALID 32'h{_bitset(MOD_SCHEME_CODES.values(), 32):08x}\n")
        f.write(f"`define HDR_CRC_VALID 8'h{_bitset(CRC_SCHEME_CODES.values(), 8):02x}\n")
        f.write(f"`define HDR_FEC_VALID 32'h{_bitset(FEC_SCHEME_CODES.values(), 32):08x}\n\n")
        f.write("`endif\n")
    return [hdr, mem, bps_mem, sel_mem]


def emit_chanest(ofdm: Ofdm, out_dir: str) -> list:
    """Interpolation ROM + pilot reciprocals for the LS channel estimator.

    spectracuda's LSChannelEstimator (spectracuda/channel/ls.py) does two
    things: `h_pilot = rx_pilots / tx_pilots`, then linear interpolation
    across every subcarrier via `np.interp`. Both become table lookups
    here, which is the whole reason the generator exists.

    THE DIVISION DISAPPEARS. tx_pilots are known constants, so 1/tx_pilot
    is a constant too -- emitted as a ROM rather than computed. For this
    configuration every pilot is exactly +1.0, so the reciprocals are +1
    and the "division" is a pass-through; the ROM is still emitted so a
    configuration with different pilot values keeps working without an
    RTL change.

    THE INTERPOLATION DIVISION ALSO DISAPPEARS. np.interp computes
    (k - p_left) / (p_right - p_left) per bin. Both terms are known at
    generation time, so the quotient is baked into a per-bin weight and
    the hardware does one multiply-accumulate:
        h[k] = h_left + (h_right - h_left) * w[k]
    Pilot gaps here are 32,32,32,62,32,32,32 -- mostly powers of two, but
    the 62 across the guard band is not, which is exactly why this is a
    generated table and not a shift.

    Edge bins outside the pilot span are CLAMPED, matching np.interp's
    own behaviour (it holds the end value rather than extrapolating).
    Those entries set left == right so the interpolation term is zero.
    """
    import numpy as _np
    os.makedirs(out_dir, exist_ok=True)
    written = []

    # Read from the CONFIGURED ESTIMATOR, not from ofdm.grid. Ofdm builds
    # LSChannelEstimator with pilot_indices=_train_known_indices and
    # tx_pilots=the training symbol's values there (ofdm.py:525-538) --
    # 224 known subcarriers, not the 8 pilot tones. Re-deriving them from
    # the grid produced an 8-entry table that silently disagreed with the
    # golden model. Take values off the object that owns them.
    pilots = _np.asarray(ofdm.channel_estimator.pilot_indices).astype(int)
    tx_p = _np.asarray(ofdm.channel_estimator.tx_pilots).ravel()
    n_pilot = len(pilots)
    n_fft = ofdm.fft_size
    slot_w = max(1, int(_np.ceil(_np.log2(n_pilot))))

    lines = []
    for k in range(n_fft):
        if k <= pilots[0]:
            li = ri = 0
            w = 0.0
        elif k >= pilots[-1]:
            li = ri = n_pilot - 1
            w = 0.0
        else:
            li = int(_np.searchsorted(pilots, k, side="right") - 1)
            ri = li + 1
            w = (k - pilots[li]) / float(pilots[ri] - pilots[li])
        wq = int(_np.floor(w * (1 << 15) + 0.5))
        if wq > (1 << 15) - 1:
            wq = (1 << 15) - 1
        word = (li << (slot_w + 16)) | (ri << 16) | (wq & 0xFFFF)
        lines.append(f"{word:08x}")

    path = os.path.join(out_dir, "chanest_interp.mem")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    written.append(path)

    # 1/tx_pilot, Q15 complex.
    #
    # Every reference value here has magnitude exactly 1 (the training
    # symbol is QPSK and the pilot bins are +1), so 1/tx == conj(tx) and
    # the "division" is a conjugate. The reciprocal is still computed and
    # emitted properly rather than assumed, so a waveform whose reference
    # symbols are not unit-magnitude keeps working.
    # Q14, NOT Q15. Every reciprocal here has magnitude 1, and 1.0 in Q15
    # is 32768 -- which does not fit a signed 16-bit field and wraps to
    # -32768. That flipped the sign of exactly the bins whose reference
    # value was +1 (the clamped edge and the first/last reference bin),
    # while every other bin matched to three decimals: a small, localised
    # wrong answer rather than an obvious break.
    #
    # Identical failure to ap_fixed<16,1> being unable to hold 1.0, which
    # this project already hit once in hls/gen/emit.py -- hence the
    # explicit range check below rather than trusting the format.
    RECIP_FRAC = 14
    recip = []
    lim = (1 << 15) - 1
    for z in tx_p:
        r = 1.0 / complex(z)
        rr = int(_np.floor(r.real * (1 << RECIP_FRAC) + 0.5))
        ri_ = int(_np.floor(r.imag * (1 << RECIP_FRAC) + 0.5))
        if not (-lim - 1 <= rr <= lim and -lim - 1 <= ri_ <= lim):
            raise ValueError(
                f"1/tx_pilot = {r} does not fit Q{RECIP_FRAC} in 16 bits "
                f"(got {rr}, {ri_}). Reduce RECIP_FRAC or widen the field; "
                f"do NOT let it wrap."
            )
        recip.append(f"{((rr & 0xFFFF) << 16) | (ri_ & 0xFFFF):08x}")
    path = os.path.join(out_dir, "pilot_recip.mem")
    with open(path, "w") as f:
        f.write("\n".join(recip) + "\n")
    written.append(path)

    hdr = _banner("chanest_params.vh -- LS estimator tables", ofdm)
    hdr += "`ifndef CHANEST_PARAMS_VH\n`define CHANEST_PARAMS_VH\n\n"
    hdr += f"`define CE_N_PILOT {n_pilot}\n"
    hdr += f"`define CE_SLOT_W {slot_w}\n"
    hdr += f"`define CE_N_FFT {n_fft}\n"
    hdr += f"`define CE_RECIP_FRAC {RECIP_FRAC}\n"
    hdr += f'`define CE_INTERP_MEM "{os.path.abspath(os.path.join(out_dir, "chanest_interp.mem"))}"\n'
    hdr += f'`define CE_RECIP_MEM "{os.path.abspath(os.path.join(out_dir, "pilot_recip.mem"))}"\n'
    # Summarise rather than dump: there are 224 reference bins here, and
    # a 224-element list in a header is noise, not documentation. Report
    # the span and the gaps that actually need interpolating.
    gaps = _np.diff(pilots)
    holes = [(int(pilots[i]), int(pilots[i + 1]))
             for i in _np.nonzero(gaps > 1)[0]]
    hdr += (f"\n// {len(pilots)} reference bins, "
            f"{int(pilots[0])}..{int(pilots[-1])}\n"
            f"// interpolated spans (gap > 1): {holes}\n"
            f"// bins below {int(pilots[0])} and above {int(pilots[-1])} "
            f"are clamped, matching np.interp\n")
    hdr += "\n`endif\n"
    path = os.path.join(out_dir, "chanest_params.vh")
    with open(path, "w") as f:
        f.write(hdr)
    written.append(path)
    return written


# Keep this block LAST -- it must sit below every function it calls.
# Appending a new emitter after it fails with a NameError only when the
# module is RUN, not when it is imported, so tests would not catch it.
def emit_eq(ofdm: Ofdm, out_dir: str) -> list:
    """Reciprocal ROM and scaling constants for the MMSE equalizer.

    spectracuda's MMSEEqualizer (spectracuda/equalizer/mmse.py) computes
        w = conj(H) / (|H|^2 + noise_var);  y = rx * w
    Unlike the channel estimator's two divisions, THIS denominator is not
    a waveform constant -- it depends on the measured channel -- so it
    cannot be evaluated at generate time. A real reciprocal is needed.

    It does not need to be a divider, though. The denominator is real and
    positive, so normalizing it to a mantissa in [1,2) and looking up
    1/mantissa is enough. How big that ROM must be was MEASURED on real
    (rx, H) pairs rather than assumed -- the consumer is a hard-decision
    demapper, whose tolerance is far looser than full precision:

        5 bits (32 entries)  -> 0.654% EVM
        7 bits (128)         -> 0.166%
        8 bits (256)         -> 0.084%   <- chosen
        12 bits (4096)       -> 0.005%

    256 entries of 16 bits is ~4 kbit. openofdm spends 1,784 LUT on a
    div_gen instance for the same job.

    Fixed-point contract, with rx and H both Q12 (H_W from ls_chanest):
        den   = |H|^2 + noise_var                 -> Q24
        E     = index of den's most significant bit
        m     = den / 2^E, in [1,2)
        LUT   = round(2^15 / m)                   -> (16384, 32768], UNSIGNED
        num   = rx * conj(H)                      -> Q24
        y_q12 = (num * LUT) >> (3 + E)
    The final shift is (3 + E) and not (15 + E) because y is wanted in
    Q12 while num and den are both Q24: 24 - 24 + 12 - 15 = -3.

    The LUT is UNSIGNED on purpose. 1/m at m=1 is exactly 1.0, which in
    Q15 is 32768 -- the same value that does not fit a SIGNED 16-bit field
    and silently wrapped in the channel estimator's reciprocal table.
    """
    import numpy as _np
    os.makedirs(out_dir, exist_ok=True)
    written = []

    lut_bits = 8
    n = 1 << lut_bits
    frac = 15
    entries = []
    for i in range(n):
        m = 1.0 + (i + 0.5) / n          # mantissa bin centre, [1,2)
        v = int(_np.floor((1 << frac) / m + 0.5))
        if not (0 < v <= 0xFFFF):
            raise ValueError(f"reciprocal {v} does not fit 16 unsigned bits")
        entries.append(f"{v:04x}")
    path = os.path.join(out_dir, "eq_recip.mem")
    with open(path, "w") as f:
        f.write("\n".join(entries) + "\n")
    written.append(path)

    nv = float(getattr(ofdm.equalizer, "noise_var", 1e-3))
    nv_q24 = int(_np.floor(nv * (1 << 24) + 0.5))

    hdr = _banner("eq_params.vh -- MMSE equalizer constants", ofdm)
    hdr += "`ifndef EQ_PARAMS_VH\n`define EQ_PARAMS_VH\n\n"
    hdr += f"`define EQ_LUT_BITS {lut_bits}\n"
    hdr += f"`define EQ_LUT_FRAC {frac}\n"
    hdr += f"`define EQ_NOISE_VAR_Q24 32'd{nv_q24}   // noise_var = {nv}\n"
    hdr += f"`define EQ_OUT_SHIFT 3   // 24 - 24 + 12 - 15\n"
    hdr += f'`define EQ_RECIP_MEM "{os.path.abspath(path)}"\n'
    hdr += "\n`endif\n"
    path = os.path.join(out_dir, "eq_params.vh")
    with open(path, "w") as f:
        f.write(hdr)
    written.append(path)
    return written


def emit_demap(ofdm: Ofdm, out_dir: str) -> list:
    """Per-scheme constants for the hard-decision demapper.

    spectracuda's rule (spectracuda/modem/mapper.py:212-220) is, per axis:
        level = clip(round(x/norm + (m-1)) / 2), 0, m-1)
        gray  = level ^ (level >> 1)
    with m = 2**(bits_per_symbol/2). Folding the two constants together:
        level = clip(round(x*scale + offset), 0, m-1)
        scale = 1/(2*norm),  offset = (m-1)/2
    Both depend only on the scheme, so both are emitted here.

    ALL THREE SCHEMES ARE EMITTED, not just the configured one. The
    modulation is runtime state in this waveform, from both directions:
    RX decodes `mod_scheme` from the frame header (so a receiver cannot
    know it at synthesis time), and TX changes it mid-session --
    Mac.set_tx_scheme() drives Ofdm.reconfigure_tx_scheme() off PER/BER.
    This is category 4 of the plan doc's section 2.1: every circuit
    present, a control register selects. openofdm does the same
    (rate_to_idx.v -> demodulate.v), which is what lets openwifi run
    adaptive MCS.

    Input is Q12, matching mmse_eq's output so the blocks connect with no
    rescale. `bias` folds the offset and the round-half-up constant into
    one addend, so the hardware is one multiply, one add, one shift, one
    clip.
    """
    import numpy as _np
    from spectracuda.modem import Modem
    os.makedirs(out_dir, exist_ok=True)

    IN_FRAC = 12          # Q12 input, from mmse_eq
    SCALE_FRAC = 14
    SH = IN_FRAC + SCALE_FRAC

    hdr = _banner("demap_params.vh -- hard-decision demapper constants", ofdm)
    hdr += "`ifndef DEMAP_PARAMS_VH\n`define DEMAP_PARAMS_VH\n\n"
    hdr += f"`define DM_SHIFT {SH}\n"
    hdr += "\n// scheme select, as carried on the mod_scheme control input\n"
    for code, name in enumerate(("qpsk", "qam16", "qam64")):
        m_ = Modem(name)
        half = m_.bits_per_symbol // 2
        m = 1 << half
        scale = 1.0 / (2.0 * m_._norm)
        offset = (m - 1) / 2.0
        scale_q = int(_np.floor(scale * (1 << SCALE_FRAC) + 0.5))
        bias_q = int(_np.floor(offset * (1 << SH) + 0.5)) + (1 << (SH - 1))
        u = name.upper()
        hdr += (f"`define DM_{u} {code}\n"
                f"`define DM_{u}_HALF {half}\n"
                f"`define DM_{u}_MAXLVL {m - 1}\n"
                f"`define DM_{u}_SCALE 32'sd{scale_q}\n"
                f"`define DM_{u}_BIAS 64'sd{bias_q}\n")
    hdr += "\n`endif\n"
    path = os.path.join(out_dir, "demap_params.vh")
    with open(path, "w") as f:
        f.write(hdr)
    return [path]


def emit_crc(ofdm: Ofdm, out_dir: str) -> list:
    """CRC constants, taken from spectracuda's own tables.

    NOT hardcoded, because these are not the standard named variants.
    `spectracuda/fec/crc.py:17-19` is explicit: liquid-dsp's crc8/crc16/
    crc24 run the ORIGINAL polynomials (0x07, 0x8005, 0x5D6DCB) through
    the same reflected reduction the 32-bit one uses, which is not what
    "CRC-16" names elsewhere. Deriving the reflected polynomial here with
    spectracuda's own `_reverse_word` guarantees the RTL agrees with the
    golden model by construction rather than by my reading a datasheet.

    Emitted: width, reflected polynomial, init register, and whether the
    result is complemented. crc.py applies `~key & mask` at the end.
    """
    import numpy as _np
    from spectracuda.fec import crc as _crc
    os.makedirs(out_dir, exist_ok=True)

    scheme = str(getattr(ofdm, "crc", "none"))
    if scheme in ("none", "checksum"):
        raise ValueError(f"crc={scheme!r} has no polynomial to emit")

    width_bytes = _crc._POLY_WIDTH_BYTES[scheme]
    out_width = width_bytes * 8
    poly_orig = _crc._POLY_ORIG[scheme]
    poly_ref = (_crc._reverse_byte(poly_orig) if width_bytes == 1
                else _crc._reverse_word(poly_orig, width_bytes))

    # THE REGISTER IS ALWAYS 32 BITS, whatever the scheme's own width.
    # _build_table's docstring calls this out as "load-bearing here, not
    # cosmetic": liquid's crc.c runs every variant through one 32-bit
    # reflected reduction and masks only the RESULT to the scheme width.
    # Sizing the register to the scheme instead gives a plausible but
    # wrong CRC -- caught by the cross-check below (0xf726 vs 0x5c27).
    REG_W = 32
    init = int(_crc._REG_MASK)
    out_mask = (1 << out_width) - 1

    # Cross-check the constants against spectracuda by running the
    # reduction here and comparing one real key. A wrong reflected
    # polynomial still produces plausible-looking CRCs, so this is
    # checked rather than trusted.
    msg = bytes(range(64))
    reg = init
    for b in msg:
        reg ^= b
        for _ in range(8):
            reg = (reg >> 1) ^ (poly_ref if (reg & 1) else 0)
        reg &= (1 << REG_W) - 1
    mine = (~reg) & ((1 << REG_W) - 1) & out_mask
    theirs = int(_np.asarray(_crc.CRC(scheme).generate_key(
        _np.frombuffer(msg, dtype=_np.uint8)[None, :])).ravel()[0])
    if mine != theirs:
        raise ValueError(
            f"emitted {scheme} constants give 0x{mine:0{out_width//4}x} but "
            f"spectracuda gives 0x{theirs:0{out_width//4}x} -- the reflected "
            f"polynomial or init value is wrong"
        )

    hdr = _banner(f"crc_params.vh -- {scheme} constants", ofdm)
    hdr += "`ifndef CRC_PARAMS_VH\n`define CRC_PARAMS_VH\n\n"
    hdr += f"// {scheme}: original poly 0x{poly_orig:x}, reflected 0x{poly_ref:x}\n"
    hdr += f"// verified against spectracuda: CRC(bytes(range(64))) = 0x{theirs:0{out_width//4}x}\n"
    hdr += f"// Register is 32 bits for EVERY scheme; only the output is\n"
    hdr += f"// masked to the scheme width. See crc.py's _build_table docstring.\n"
    hdr += f"`define CRC_REG_W {REG_W}\n"
    hdr += f"`define CRC_OUT_W {out_width}\n"
    hdr += f"`define CRC_POLY {REG_W}'h{poly_ref:08x}\n"
    hdr += f"`define CRC_INIT {REG_W}'h{init:08x}\n"
    hdr += "`define CRC_COMPLEMENT 1\n"
    hdr += "\n`endif\n"
    path = os.path.join(out_dir, "crc_params.vh")
    with open(path, "w") as f:
        f.write(hdr)
    return [path]


